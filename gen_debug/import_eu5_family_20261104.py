"""Import EU5 family names and arms for existing CK3 dynasties/houses.

The source inputs and the original converter are retained in the named backup.
Run with --dry-run first. Does not alter dynasty relationships or characters.
After importing, apply fix_eu5_family_coa_aspect_20261104.py to correct the
3:2 EU5 texture aspect for CK3's square coat-of-arms canvas.
"""
from pathlib import Path
import importlib.util
import json
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parent.parent
BACKUP = Path('F:/备份/EU5_Modern_Borders_noshape/_backup_20261104_214624_eu5_dynasties')
EU = BACKUP / 'eu5'
SOURCE = BACKUP / 'pipeline' / '_gen_eu5_coa.py'
spec = importlib.util.spec_from_file_location('eu5_coa_converter', SOURCE)
coa = importlib.util.module_from_spec(spec)
spec.loader.exec_module(coa)
coa.PFX = 'eu5dyn_'
coa.SQUASH = False
coa.WIDEN = False
coa.COLOR_SRC = str(EU / 'common/named_colors/01_coa.txt')

def read(p):
    return p.read_text(encoding='utf-8-sig')

def blocks(p):
    return dict(coa.parse_top_blocks(read(p)))

def localizations(lang, needed):
    root = EU / 'localization' / lang
    files = list(root.rglob('*.yml'))
    def order(p):
        n = p.name
        return (0 if n.startswith('dynasty_names_') else
                1 if n.startswith('character_names_dynamic_') else
                2 if n.startswith('character_names_') else
                3 if n.startswith('location_names_') else 4, str(p))
    result = {}
    pat = re.compile(r'^\s*([\w.\-]+):\d*\s*"(.*)"\s*(?:#.*)?$')
    for p in sorted(files, key=order):
        for line in read(p).splitlines():
            m = pat.match(line)
            if m and m.group(1) in needed and m.group(1) not in result:
                result[m.group(1)] = m.group(2)
    return result

dyn_path = ROOT / 'common/dynasties/zz_eu5_dynasties.txt'
house_path = ROOT / 'common/dynasty_houses/zz_eu5_merged_houses.txt'
alias_path = ROOT / 'common/coat_of_arms/coat_of_arms/95_zz_eu5_dynasty_aliases.txt'
dyn = blocks(dyn_path)
houses = blocks(house_path)
setup = dict(coa.parse_top_blocks(blocks(EU / 'setup/1337/04_dynasties.txt')['dynasty_manager']))
source_text = read(EU / 'common/coat_of_arms/coat_of_arms/pre_scripted_dynasties.txt')
source = dict(coa.parse_top_blocks(source_text))
coa.VARS = coa.Vars(coa.parse_vars(source_text))
palette, palette_order = coa.load_palette()

def setup_name(key):
    body = setup.get(key, '')
    m = re.search(r'\bname\s*=\s*\{\s*name\s*=\s*"?([\w.\-]+)', body)
    return m.group(1) if m else None

targets = []
for key, body in dyn.items():
    if key == 'default_dynasty':
        continue
    m = re.search(r'\bname\s*=\s*"?([\w.\-]+)', body)
    targets.append(('dynasty', key, key, m.group(1) if m else None))
for key, body in houses.items():
    m = re.search(r'\bname\s*=\s*"?([\w.\-]+)', body)
    current = m.group(1) if m else None
    candidate = key.removeprefix('house_') + '_dynasty'
    src = candidate if candidate in setup or candidate in source else current
    targets.append(('house', key, src, current))

name_keys = {src: setup_name(src) or (src if src in source else current)
             for _, _, src, current in targets}
needed = {v for v in name_keys.values() if v} | {src for _, _, src, _ in targets if src}
languages = ['english', 'simp_chinese', 'french', 'german', 'spanish',
             'russian', 'polish', 'braz_por', 'japanese', 'korean', 'turkish']
loc = {lang: localizations(lang, needed) for lang in languages}
arms = []
missing_arm = []
used_subs = set()
for kind, target, src, current in targets:
    if src in source:
        arms.append((target, src, coa.transform(source[src], palette, used_subs)))
    else:
        missing_arm.append((kind, target, src))
if used_subs:
    raise ValueError('Unexpected family coat parent dependencies: ' + repr(sorted(used_subs)))

generated = {}
refs = set()
arm_lines = ['# EU5 family coat of arms; generated by gen_debug/import_eu5_family_20261104.py', '']
for target, src, body in arms:
    arm_lines.extend(['# EU5 ' + src, coa.emit_block(target, body)])
    refs.update(re.findall(r'"(eu5dyn_[^"\n]+\.dds)"', body))
generated[ROOT / 'common/coat_of_arms/coat_of_arms/zzzz_eu5_family_arms.txt'] = '\n'.join(arm_lines)
colors = ['# EU5 family-only colors', 'colors = {']
for name in palette_order:
    kind, vals = palette[name]
    colors.append('\teu5dyn_' + name + ' = ' + kind + ' { ' + ' '.join(vals) + ' }')
colors.append('}')
generated[ROOT / 'common/named_colors/zz_eu5_family_colors.txt'] = '\n'.join(colors) + '\n'

# Assign separate localization keys: this avoids changing existing shared CK3/EU5 keys.
def rewrite_names(path, kind):
    text = read(path)
    target_map = {k: (src, old) for t, k, src, old in targets if t == kind}
    key = None
    out = []
    changed = 0
    for line in text.splitlines(keepends=True):
        m = re.match(r'^([\w.\-]+)\s*=\s*\{', line)
        if m:
            key = m.group(1)
        if key in target_map and re.match(r'^\s*name\s*=', line):
            src, old = target_map[key]
            namekey = name_keys.get(src)
            if namekey and any(namekey in d for d in loc.values()):
                line = re.sub(r'(\bname\s*=\s*)"?[\w.\-]+"?', r'\1"eu5_family_' + key + '"', line, count=1)
                changed += 1
        out.append(line)
    generated[path] = ''.join(out)
    return changed

name_count = rewrite_names(dyn_path, 'dynasty') + rewrite_names(house_path, 'house')
missing_loc = {}
for lang in languages:
    lines = ['l_' + lang + ':']
    missing_loc[lang] = []
    for kind, target, src, old in targets:
        key = name_keys.get(src)
        if not key or not any(key in d for d in loc.values()):
            missing_loc[lang].append(target)
            continue
        # Other languages fall back to the EU5 English value, preserving provenance.
        value = loc[lang].get(key, loc['english'].get(key))
        if value is None:
            missing_loc[lang].append(target)
            continue
        lines.append(' eu5_family_' + target + ':0 "' + value + '"')
    generated[ROOT / 'localization' / lang / ('zzzz_eu5_family_l_' + lang + '.yml')] = '\n'.join(lines) + '\n'

generated[alias_path] = '# EU5 family arms are defined in zzzz_eu5_family_arms.txt.\n# Former CK3 family aliases are preserved in the timestamped backup.\n'
textures = []
missing_tex = []
for ref in sorted(refs):
    original = ref.removeprefix('eu5dyn_')
    sub = ('colored_emblems' if original.startswith('ce_') else
           'textured_emblems' if original.startswith('te_') else
           'patterns' if original.startswith('pattern_') else None)
    if not sub:
        missing_tex.append(original)
        continue
    src = EU / 'gfx/coat_of_arms' / sub / original
    dst = ROOT / 'gfx/coat_of_arms' / sub / ref
    if not src.is_file():
        missing_tex.append(str(src))
    else:
        textures.append((src, dst))
if missing_tex:
    raise ValueError('Missing EU5 textures: ' + repr(missing_tex))
if len({x[0] for x in arms}) != len(arms):
    raise ValueError('Duplicate family coat keys')
if any(p.exists() for _, p in textures):
    raise FileExistsError('A destination texture already exists; back it up before replacing it')
for p in generated:
    if p.exists() and p not in (dyn_path, house_path, alias_path):
        raise FileExistsError('A generated destination already exists; back it up first: ' + str(p))
report = {'targets': len(targets), 'dynasties': len(dyn)-int('default_dynasty' in dyn),
          'houses': len(houses), 'coat_definitions': len(arms), 'name_fields_updated': name_count,
          'textures': len(textures), 'missing_arms': missing_arm, 'missing_localizations': missing_loc,
          'family_name_source': {target: {'eu5_dynasty': src, 'eu5_name_key': name_keys.get(src),
                                         'original_mod_name_key': old} for _, target, src, old in targets}}
print(json.dumps({k: (len(v) if k == 'missing_arms' else
                      {lang: len(miss) for lang, miss in v.items()} if k == 'missing_localizations' else v)
                  for k, v in report.items() if k != 'family_name_source'}, ensure_ascii=False, indent=2))
if '--dry-run' in sys.argv:
    sys.exit(0)
for src, dst in textures:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)
for path, body in generated.items():
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding='utf-8-sig', newline='\n')
(ROOT / 'gen_debug/eu5_family_import_report_20261104.json').write_text(
    json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
